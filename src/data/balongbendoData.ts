const HOURS = 60 * 60 * 1000;
const now = Date.now();

function isoAgo(hoursAgo: number): string {
  return new Date(now - hoursAgo * HOURS).toISOString();
}

function isoFrom(baseIso: string, hoursLater: number): string {
  return new Date(new Date(baseIso).getTime() + hoursLater * HOURS).toISOString();
}

